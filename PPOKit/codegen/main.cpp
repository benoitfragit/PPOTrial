/**
 * @file PPOKit/codegen/main.cpp
 * @brief Command-line generator of PPOKit headers.
 *
 *     ppokit-codegen layout   <task.json>              <output.hpp>
 *     ppokit-codegen networks <task.json> <graph.json> <output.hpp>
 *     ppokit-codegen embed    <namespace> <Name>=<file>... <output.hpp>
 *
 * `layout` writes the constants of the task (offsets, names, hash); `networks` writes
 * the rl_tools types of the networks described in graph.json; `embed` writes text files
 * as string constants (e.g. task.json and graph.json, so that a program never depends on
 * its working directory). The build system runs
 * the generator only when an input changed, and the header is then always rewritten
 * so that its timestamp records the generation. Errors are printed as
 * "<file>: <key path>: <message>".
 */
#include "ppokit/artifacts/atomic_file.hpp"
#include "ppokit/schema/network_schema.hpp"
#include "ppokit/schema/task_codegen.hpp"

#include <exception>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <sstream>
#include <stdexcept>
#include <string>

namespace {

/** @brief Writes the generated header text as is. */
struct HeaderWriter final
{
    std::string const& text;
    void operator()(std::ostream& stream) const { stream << text; }
};

void WriteHeader(std::filesystem::path const& output, std::string const& header)
{
    ppokit::artifacts::AtomicWriteOptions options;
    options.mode = std::ios::binary;
    ppokit::artifacts::WriteFileAtomically(output, HeaderWriter{header}, options, "ppokit-codegen");
}

/** @brief Delimiter of the raw string literals written by `embed`. */
constexpr char const* EmbedDelimiter = "PPOKIT_EMBED";
/** @brief MSVC refuses single string literals above 16 KiB; keep a margin. */
constexpr std::size_t EmbedLimit = 16000;

std::string ReadText(std::filesystem::path const& path)
{
    std::ifstream file(path, std::ios::binary);
    if (!file)
    {
        throw std::runtime_error(path.string() + ": cannot open the file");
    }
    std::stringstream text;
    text << file.rdbuf();
    return text.str();
}

/**
 * @brief Header with one `inline constexpr char <Name>[]` per `<Name>=<file>` entry.
 * @throws std::runtime_error for a malformed entry, a file too long for one literal or
 *         containing the raw string delimiter.
 */
std::string GenerateEmbeddedHeader(std::string const& nameSpace, int count, char** entries)
{
    std::string header = "// Generated by ppokit-codegen embed: do not edit.\n#pragma once\n\nnamespace " + nameSpace
        + " {\n";
    for (int index = 0; index < count; ++index)
    {
        std::string const entry = entries[index];
        std::size_t const equals = entry.find('=');
        if (equals == std::string::npos || equals == 0)
        {
            throw std::runtime_error("embed: expected <Name>=<file>, got '" + entry + "'");
        }
        std::string const name = entry.substr(0, equals);
        std::filesystem::path const file = entry.substr(equals + 1);
        std::string const text = ReadText(file);
        if (text.size() > EmbedLimit)
        {
            throw std::runtime_error(file.string() + ": too long to embed (" + std::to_string(text.size()) + " bytes)");
        }
        if (text.find(std::string(")") + EmbedDelimiter + "\"") != std::string::npos)
        {
            throw std::runtime_error(file.string() + ": contains the embedding delimiter");
        }
        header += "\n/** @brief Content of " + file.filename().string() + ". */\ninline constexpr char " + name
            + "[] = R\"" + EmbedDelimiter + "(" + text + ")" + EmbedDelimiter + "\";\n";
    }
    return header + "\n} // namespace " + nameSpace + "\n";
}

int PrintUsage()
{
    std::cerr << "usage: ppokit-codegen layout <task.json> <output.hpp>\n"
                 "       ppokit-codegen networks <task.json> <graph.json> <output.hpp>\n"
                 "       ppokit-codegen embed <namespace> <Name>=<file>... <output.hpp>\n";
    return 2;
}

} // namespace

int main(int argc, char** argv)
{
    if (argc < 2)
    {
        return PrintUsage();
    }
    std::string const command = argv[1];
    try
    {
        if (command == "layout" && argc == 4)
        {
            std::filesystem::path const taskFile = argv[2];
            auto const task = ppokit::schema::LoadTaskSchema(taskFile);
            WriteHeader(argv[3], ppokit::schema::GenerateTaskLayoutHeader(task, taskFile.filename().string()));
            return 0;
        }
        if (command == "networks" && argc == 5)
        {
            std::filesystem::path const graphFile = argv[3];
            auto const task = ppokit::schema::LoadTaskSchema(argv[2]);
            auto const networks = ppokit::schema::LoadNetworkSchema(graphFile, task);
            WriteHeader(argv[4],
                ppokit::schema::GenerateNetworksHeader(networks, task, graphFile.filename().string()));
            return 0;
        }
        if (command == "embed" && argc >= 5)
        {
            WriteHeader(argv[argc - 1], GenerateEmbeddedHeader(argv[2], argc - 4, argv + 3));
            return 0;
        }
        return PrintUsage();
    }
    catch (std::exception const& error)
    {
        std::cerr << "ppokit-codegen: " << error.what() << '\n';
        return 1;
    }
}
